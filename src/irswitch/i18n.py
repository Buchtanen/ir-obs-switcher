class Translator:
    """Translation helper class."""

    def __init__(self, language: str = DEFAULT_LANGUAGE):
        """
        Initialize translator.

        Args:
            language: Language code (CS, EN, DE, FR, SP, PL, HU)
        """
        language = language.upper()
        if language not in SUPPORTED_LANGUAGES:
            language = DEFAULT_LANGUAGE
        self.language = language
        self.translations = TRANSLATIONS.get(language, TRANSLATIONS[DEFAULT_LANGUAGE])

    def translate(self, key: str, **kwargs) -> str:
        """
        Translate a key to the current language.

        Args:
            key: Translation key
            **kwargs: Format arguments for the translation string

        Returns:
            Translated string, or key if not found
        """
        translation = self.translations.get(key, key)
        if kwargs:
            try:
                return translation.format(**kwargs)
            except (KeyError, ValueError):
                return translation
        return translation

    def t(self, key: str, **kwargs) -> str:
        """Short alias for translate."""
        return self.translate(key, **kwargs)


# Global translator instance (will be initialized with config language)
_translator: Translator | None = None


def set_language(language: str) -> None:
    """Set the global language."""
    global _translator
    _translator = Translator(language)


def get_translator() -> Translator:
    """Get the global translator instance."""
    global _translator
    if _translator is None:
        _translator = Translator(DEFAULT_LANGUAGE)
    return _translator


def t(key: str, **kwargs) -> str:
    """Translate a key using the global translator."""
    return get_translator().translate(key, **kwargs)
